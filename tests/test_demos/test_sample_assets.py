"""
tests/test_demos/test_sample_assets.py
Verification test suite for deterministic sample assets generated by scripts/generate_sample_assets.py.
Validates dimensional invariants, CSV structure, anomaly window detection, and P&ID revision differencing.
"""
import csv
from datetime import datetime
from pathlib import Path
from PIL import Image
import pytest

from sovereign.multimodal.ocr import validate_image_file
from sovereign.vision.diff import DiffChangeType, DrawingDiffEngine


def test_inspection_scan_dimensions_and_safety(samples_dir: Path):
    """
    Validates samples/refinery_vessel_inspection_v301.png:
    - Exists and passes validate_image_file() security checks.
    - Dimensions are exactly 1240 x 1754 pixels (A4 proportions).
    - Image mode is RGB.
    - File size is under 5 MB.
    """
    scan_path = samples_dir / "refinery_vessel_inspection_v301.png"
    assert scan_path.exists(), f"Sample inspection scan missing at {scan_path}"

    validated = validate_image_file(scan_path)
    assert validated == scan_path.resolve()

    file_size_mb = scan_path.stat().st_size / (1024 * 1024)
    assert file_size_mb < 5.0, f"File size too large: {file_size_mb:.2f} MB"

    with Image.open(scan_path) as img:
        assert img.size == (1240, 1754), f"Expected (1240, 1754), got {img.size}"
        assert img.mode == "RGB", f"Expected RGB mode, got {img.mode}"


def test_historian_csv_row_count_and_anomalies(samples_dir: Path):
    """
    Validates samples/historian_sensor_telemetry.csv:
    - Exists and has exactly 10,001 lines (1 header + 10,000 data rows).
    - Header matches: ['timestamp', 'machine_id', 'vib_rms_g', 'peak_accel_g', 'bearing_temp_c', 'shaft_speed_rpm'].
    - Every row has valid ISO timestamp and valid numeric fields.
    - Rows 450 to 520 exhibit transient anomaly: vib_rms_g > 5.0g and bearing_temp_c > 90.0 C.
    - Baseline rows exhibit vib_rms_g between 0.8 and 1.5g.
    """
    csv_path = samples_dir / "historian_sensor_telemetry.csv"
    assert csv_path.exists(), f"Sample historian CSV missing at {csv_path}"

    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.reader(f)
        rows = list(reader)

    assert len(rows) == 10001, f"Expected 10001 lines, got {len(rows)}"

    header = rows[0]
    expected_header = ["timestamp", "machine_id", "vib_rms_g", "peak_accel_g", "bearing_temp_c", "shaft_speed_rpm"]
    assert header == expected_header, f"Header mismatch: {header}"

    anomaly_detected = False
    max_vib = 0.0
    max_temp = 0.0

    for idx, row in enumerate(rows[1:], start=1):
        assert len(row) == 6, f"Row {idx} malformed: {row}"
        t_str, machine, vib_str, peak_str, temp_str, speed_str = row

        # Parse timestamp
        # Handle 'Z' suffix
        ts_clean = t_str.replace("Z", "+00:00")
        dt = datetime.fromisoformat(ts_clean)
        assert dt is not None

        assert machine == "PUMP-301-B"

        vib = float(vib_str)
        temp = float(temp_str)
        speed = float(speed_str)

        if vib > max_vib:
            max_vib = vib
        if temp > max_temp:
            max_temp = temp

        if 450 <= idx <= 520:
            if vib >= 5.0 and temp >= 90.0:
                anomaly_detected = True
        else:
            # Baseline assertion
            assert 0.7 <= vib <= 1.6, f"Row {idx} baseline vibration out of range: {vib}"
            assert 48.0 <= temp <= 58.0, f"Row {idx} baseline temp out of range: {temp}"

    assert anomaly_detected, f"Anomaly not detected in transient window (max_vib={max_vib}, max_temp={max_temp})"
    assert max_vib >= 5.0, f"Max vibration {max_vib} did not reach 5.0g"
    assert max_temp >= 90.0, f"Max temperature {max_temp} did not reach 90.0 C"


def test_pid_revisions_geometry_and_diffs(samples_dir: Path):
    """
    Validates samples/pid_drawing_rev_a.png and samples/pid_drawing_rev_b.png:
    - Both exist, have dimensions 1600 x 1200, mode RGB.
    - DrawingDiffEngine.compare_revisions() detects exactly 3 discrete diff regions.
    - Change types contain ADDED, REMOVED, and MODIFIED.
    - All bounding box coordinates are normalized in [0.0, 1.0].
    """
    path_a = samples_dir / "pid_drawing_rev_a.png"
    path_b = samples_dir / "pid_drawing_rev_b.png"

    assert path_a.exists(), f"Rev A drawing missing at {path_a}"
    assert path_b.exists(), f"Rev B drawing missing at {path_b}"

    with Image.open(path_a) as im_a:
        assert im_a.size == (1600, 1200)
        assert im_a.mode == "RGB"

    with Image.open(path_b) as im_b:
        assert im_b.size == (1600, 1200)
        assert im_b.mode == "RGB"

    boxes = DrawingDiffEngine.compare_revisions(path_a, path_b)

    # Validate exactly 3 diff regions
    assert len(boxes) == 3, f"Expected exactly 3 diff regions, got {len(boxes)}: {[b.model_dump() for b in boxes]}"

    change_types = {b.change_type for b in boxes}
    assert DiffChangeType.ADDED in change_types, f"ADDED change type missing in {change_types}"
    assert DiffChangeType.REMOVED in change_types, f"REMOVED change type missing in {change_types}"
    assert DiffChangeType.MODIFIED in change_types, f"MODIFIED change type missing in {change_types}"

    for b in boxes:
        ymin, xmin, ymax, xmax = b.box_2d
        assert 0.0 <= ymin < ymax <= 1.0, f"Invalid vertical bounds: {b.box_2d}"
        assert 0.0 <= xmin < xmax <= 1.0, f"Invalid horizontal bounds: {b.box_2d}"
        assert b.pixel_count >= 20, f"Pixel count too low: {b.pixel_count}"
