"""
src/sovereign/deliverables/xlsx.py
Native Microsoft Excel (.xlsx) deliverable generator with live recalculable formulas,
3-tier visual hierarchy (inputs, calculations, compliance), formula injection
sanitization, and Phase 1 LineageEngine packaging.
Complies with DELV-02, T-04-02 (formula sanitization), and T-04-04 (path fencing).
"""
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Union
import uuid

import openpyxl
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from sovereign.deliverables.docx import validate_output_path
from sovereign.lineage.engine import LineageEngine
from sovereign.lineage.models import (
    DeliverableInfo,
    LineageMetadata,
    ModelInfo,
)
from sovereign.tools.builtin.files import PathSecurityViolation

# 3-Tier Visual Styling Constants
BLUE_FILL = PatternFill(start_color="D9E1F2", end_color="D9E1F2", fill_type="solid")     # Tier 1: Soft Blue (Inputs)
YELLOW_FILL = PatternFill(start_color="FFF2CC", end_color="FFF2CC", fill_type="solid")   # Tier 2: Soft Amber (Formulas)
GREEN_FILL = PatternFill(start_color="E2EFDA", end_color="E2EFDA", fill_type="solid")    # Tier 3: Soft Green (Pass/Safe)
RED_FILL = PatternFill(start_color="FCE4D6", end_color="FCE4D6", fill_type="solid")      # Tier 3: Soft Red (Fail/Unsafe)
HEADER_FILL = PatternFill(start_color="1F497D", end_color="1F497D", fill_type="solid")   # Corporate Navy
SUBHEADER_FILL = PatternFill(start_color="F2F2F2", end_color="F2F2F2", fill_type="solid")

WHITE_BOLD_FONT = Font(name="Calibri", size=10.5, bold=True, color="FFFFFF")
TITLE_FONT = Font(name="Calibri", size=15, bold=True, color="1F497D")
SUBTITLE_FONT = Font(name="Calibri", size=10, italic=True, color="595959")
SECTION_FONT = Font(name="Calibri", size=12, bold=True, color="1F497D")
BOLD_FONT = Font(name="Calibri", size=10.5, bold=True)
NORMAL_FONT = Font(name="Calibri", size=10.5)
STATUS_FONT = Font(name="Calibri", size=11, bold=True, color="0F5132")

THIN_BORDER = Border(
    left=Side(style="thin", color="D0D0D0"),
    right=Side(style="thin", color="D0D0D0"),
    top=Side(style="thin", color="D0D0D0"),
    bottom=Side(style="thin", color="D0D0D0"),
)

FORMULA_TRIGGER_CHARS = ("=", "+", "-", "@")


def sanitize_cell_text(text: Any) -> Any:
    """
    Sanitizes cell text against Dynamic Data Exchange (DDE) and CSV/formula injection attacks.
    If text starts with '=', '+', '-', or '@', prefixes with a single apostrophe (') to disable execution.
    Non-string values or strings not starting with trigger characters are returned unmodified.
    """
    if not isinstance(text, str):
        return text
    if text and text[0] in FORMULA_TRIGGER_CHARS:
        return f"'{text}"
    return text


class XlsxDeliverableGenerator:
    """
    Generates native Microsoft Excel (.xlsx) workbooks featuring live recalculable formulas,
    color-coded input/calculation/compliance tiers, formula injection defenses, and embedded lineage.
    """

    def __init__(self, allowed_root: Optional[Union[str, Path]] = None):
        self.allowed_root = Path(allowed_root).resolve() if allowed_root else None

    @classmethod
    def generate_calculation_workbook(
        cls,
        output_path: Union[str, Path],
        title: str,
        standard_ref: str,
        inputs: List[Dict[str, Any]],
        calculations: List[Dict[str, Any]],
        conclusion_formula: str,
        lineage_metadata: Optional[LineageMetadata] = None,
        facility: Optional[str] = None,
        equipment_tag: Optional[str] = None,
        allowed_root: Optional[Union[str, Path]] = None,
    ) -> Path:
        """
        Creates an engineering calculation workbook with live formulas and 3-tier styling.
        """
        resolved_path = validate_output_path(output_path, allowed_root)
        resolved_path.parent.mkdir(parents=True, exist_ok=True)

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Engineering Calculation"
        ws.views.sheetView[0].showGridLines = True

        # 1. Title Block
        ws["A1"] = sanitize_cell_text(title)
        ws["A1"].font = TITLE_FONT

        clean_std = sanitize_cell_text(standard_ref)
        sub_info = f"Governing Standard: {clean_std}"
        if facility or equipment_tag:
            clean_fac = sanitize_cell_text(facility) if facility else "N/A"
            clean_tag = sanitize_cell_text(equipment_tag) if equipment_tag else "N/A"
            sub_info += f"  |  Facility: {clean_fac}  |  Tag: {clean_tag}"
        ws["A2"] = sanitize_cell_text(sub_info)
        ws["A2"].font = SUBTITLE_FONT

        ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
        ws["A3"] = f"Generated by Sovereign AI Workbench  |  Timestamp: {ts}"
        ws["A3"].font = Font(name="Calibri", size=9, italic=True, color="7F7F7F")

        current_row = 5

        # 2. Section 1: Input Parameters (Tier 1: Soft Blue)
        ws.cell(row=current_row, column=1, value="1. Input Parameters & Operating Conditions").font = SECTION_FONT
        current_row += 1

        input_headers = ["Parameter Description", "Symbol", "Value", "Unit", "Notes / References"]
        for c_idx, h in enumerate(input_headers, start=1):
            c = ws.cell(row=current_row, column=c_idx, value=h)
            c.fill = HEADER_FILL
            c.font = WHITE_BOLD_FONT
            c.alignment = Alignment(horizontal="center" if c_idx in (2, 4) else "left", vertical="center")
            c.border = THIN_BORDER
        current_row += 1

        input_cell_map = {}
        for item in inputs:
            desc = sanitize_cell_text(item.get("name", item.get("description", "")))
            sym = sanitize_cell_text(item.get("symbol", ""))
            val = item.get("value", "")
            unit = sanitize_cell_text(item.get("unit", ""))
            notes = sanitize_cell_text(item.get("notes", item.get("citation", "")))

            # Col 1: Description
            c1 = ws.cell(row=current_row, column=1, value=desc)
            c1.font = NORMAL_FONT
            c1.border = THIN_BORDER

            # Col 2: Symbol
            c2 = ws.cell(row=current_row, column=2, value=sym)
            c2.font = BOLD_FONT
            c2.alignment = Alignment(horizontal="center")
            c2.border = THIN_BORDER

            # Col 3: Value (Tier 1: Soft Blue)
            # If string, sanitize; if numeric, write directly
            sanitized_val = sanitize_cell_text(val) if isinstance(val, str) else val
            c3 = ws.cell(row=current_row, column=3, value=sanitized_val)
            c3.fill = BLUE_FILL
            c3.font = BOLD_FONT
            c3.alignment = Alignment(horizontal="right" if isinstance(val, (int, float)) else "left")
            c3.border = THIN_BORDER

            # Track symbol to cell coordinate for formula linking
            if sym:
                input_cell_map[sym] = f"C{current_row}"

            # Col 4: Unit
            c4 = ws.cell(row=current_row, column=4, value=unit)
            c4.font = NORMAL_FONT
            c4.alignment = Alignment(horizontal="center")
            c4.border = THIN_BORDER

            # Col 5: Notes
            c5 = ws.cell(row=current_row, column=5, value=notes)
            c5.font = NORMAL_FONT
            c5.border = THIN_BORDER

            current_row += 1

        current_row += 1  # Spacing

        # 3. Section 2: Calculations & Intermediate Steps (Tier 2: Soft Amber)
        ws.cell(row=current_row, column=1, value="2. Calculations & Intermediate Engineering Formulations").font = SECTION_FONT
        current_row += 1

        calc_headers = ["Calculation Step", "Symbol", "Active Formula / Value", "Unit", "Governing Clause / Method"]
        for c_idx, h in enumerate(calc_headers, start=1):
            c = ws.cell(row=current_row, column=c_idx, value=h)
            c.fill = HEADER_FILL
            c.font = WHITE_BOLD_FONT
            c.alignment = Alignment(horizontal="center" if c_idx in (2, 4) else "left", vertical="center")
            c.border = THIN_BORDER
        current_row += 1

        calc_cell_map = {}
        for calc in calculations:
            step_name = sanitize_cell_text(calc.get("name", calc.get("step", "")))
            sym = sanitize_cell_text(calc.get("symbol", ""))
            raw_formula = calc.get("formula_excel", calc.get("formula", ""))
            unit = sanitize_cell_text(calc.get("unit", ""))
            clause = sanitize_cell_text(calc.get("clause", calc.get("notes", "")))

            # Col 1: Step Name
            c1 = ws.cell(row=current_row, column=1, value=step_name)
            c1.font = NORMAL_FONT
            c1.border = THIN_BORDER

            # Col 2: Symbol
            c2 = ws.cell(row=current_row, column=2, value=sym)
            c2.font = BOLD_FONT
            c2.alignment = Alignment(horizontal="center")
            c2.border = THIN_BORDER

            # Col 3: Active Live Formula (Tier 2: Soft Amber)
            # Ensure formula starts with = for openpyxl formula evaluation
            f_str = str(raw_formula)
            if not f_str.startswith("="):
                f_str = f"={f_str}"

            c3 = ws.cell(row=current_row, column=3, value=f_str)
            c3.fill = YELLOW_FILL
            c3.font = BOLD_FONT
            c3.alignment = Alignment(horizontal="right")
            c3.border = THIN_BORDER

            if sym:
                calc_cell_map[sym] = f"C{current_row}"

            # Col 4: Unit
            c4 = ws.cell(row=current_row, column=4, value=unit)
            c4.font = NORMAL_FONT
            c4.alignment = Alignment(horizontal="center")
            c4.border = THIN_BORDER

            # Col 5: Clause
            c5 = ws.cell(row=current_row, column=5, value=clause)
            c5.font = NORMAL_FONT
            c5.border = THIN_BORDER

            current_row += 1

        current_row += 1  # Spacing

        # 4. Section 3: Verification & Compliance Status (Tier 3: Soft Green / Red)
        ws.cell(row=current_row, column=1, value="3. Engineering Verification & Compliance Status").font = SECTION_FONT
        current_row += 1

        status_headers = ["Verification Item", "Target Condition", "Live Status Formula", "Evaluation", "Action Required"]
        for c_idx, h in enumerate(status_headers, start=1):
            c = ws.cell(row=current_row, column=c_idx, value=h)
            c.fill = HEADER_FILL
            c.font = WHITE_BOLD_FONT
            c.alignment = Alignment(horizontal="center" if c_idx in (2, 3, 4) else "left", vertical="center")
            c.border = THIN_BORDER
        current_row += 1

        # Col 1: Item
        c1 = ws.cell(row=current_row, column=1, value="Wall Thickness & Pressure Design Safety Check")
        c1.font = NORMAL_FONT
        c1.border = THIN_BORDER

        # Col 2: Target
        c2 = ws.cell(row=current_row, column=2, value="Actual Measured (t_act) >= Min Required (t_m)")
        c2.font = BOLD_FONT
        c2.alignment = Alignment(horizontal="center")
        c2.border = THIN_BORDER

        # Col 3: Live Status Formula (Tier 3: Soft Green)
        status_f = str(conclusion_formula)
        if not status_f.startswith("="):
            status_f = f"={status_f}"

        c3 = ws.cell(row=current_row, column=3, value=status_f)
        c3.fill = GREEN_FILL
        c3.font = STATUS_FONT
        c3.alignment = Alignment(horizontal="center", vertical="center")
        c3.border = THIN_BORDER

        # Col 4: Evaluation
        c4 = ws.cell(row=current_row, column=4, value="Automatic via Formula")
        c4.font = NORMAL_FONT
        c4.alignment = Alignment(horizontal="center")
        c4.border = THIN_BORDER

        # Col 5: Action
        c5 = ws.cell(row=current_row, column=5, value="Maintain standard inspection interval if PASS")
        c5.font = NORMAL_FONT
        c5.border = THIN_BORDER

        current_row += 2

        # 5. Color Legend Footer
        ws.cell(row=current_row, column=1, value="Visual Tier Legend:").font = BOLD_FONT
        ws.cell(row=current_row, column=2, value="User Input").fill = BLUE_FILL
        ws.cell(row=current_row, column=2).font = BOLD_FONT
        ws.cell(row=current_row, column=2).alignment = Alignment(horizontal="center")
        ws.cell(row=current_row, column=2).border = THIN_BORDER

        ws.cell(row=current_row, column=3, value="Live Formula").fill = YELLOW_FILL
        ws.cell(row=current_row, column=3).font = BOLD_FONT
        ws.cell(row=current_row, column=3).alignment = Alignment(horizontal="center")
        ws.cell(row=current_row, column=3).border = THIN_BORDER

        ws.cell(row=current_row, column=4, value="Safe / Pass").fill = GREEN_FILL
        ws.cell(row=current_row, column=4).font = BOLD_FONT
        ws.cell(row=current_row, column=4).alignment = Alignment(horizontal="center")
        ws.cell(row=current_row, column=4).border = THIN_BORDER

        ws.cell(row=current_row, column=5, value="Unsafe / Fail").fill = RED_FILL
        ws.cell(row=current_row, column=5).font = BOLD_FONT
        ws.cell(row=current_row, column=5).alignment = Alignment(horizontal="center")
        ws.cell(row=current_row, column=5).border = THIN_BORDER

        # 6. Auto-fit column widths
        for col in ws.columns:
            max_len = 0
            col_letter = get_column_letter(col[0].column)
            for cell in col:
                val_str = str(cell.value or "")
                # Avoid long formula strings expanding column excessively
                if val_str.startswith("="):
                    val_len = min(len(val_str), 22)
                else:
                    val_len = len(val_str)
                if val_len > max_len:
                    max_len = val_len
            ws.column_dimensions[col_letter].width = max(max_len + 5, 14)

        # Save workbook
        wb.save(resolved_path)

        # 7. Lineage Packaging
        meta = lineage_metadata
        if meta is None:
            meta = LineageMetadata(
                deliverable=DeliverableInfo(
                    file_name=resolved_path.name,
                    media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                ),
                session_id=f"session-{uuid.uuid4().hex[:8]}",
                user_id="engineer",
                user_role="Lead Engineer",
                model=ModelInfo(model_id="sovereign-local-v1", weights_sha256="0" * 64),
                audit_start_seq=0,
                audit_end_seq=1,
                audit_tip_hash="0" * 64,
            )

        LineageEngine.package_deliverable(resolved_path, meta)
        return resolved_path

    # Alias for API compatibility
    generate_calculation_sheet = generate_calculation_workbook
